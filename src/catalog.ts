export function initialModels(): Model[] {
  return entries.map(([name, primary, secondary, exercises, notes, model]) => ({
    id: uuid(),
    name,
    manufacturer: "Nautilus",
    model,
    category:
      model.includes("Cable") ||
      name.includes("cable") ||
      name === "Freedom Trainer"
        ? "Cable"
        : name.includes("Bench")
          ? "Bench"
          : "Machine",
    nickname: "",
    primary,
    secondary,
    exercises,
    notes,
    rating: null,
    comfort: null,
    adjustability: null,
    movement: null,
    favorite: false,
    photo: null,
  }));
}
